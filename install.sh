#!/bin/zsh
# Install / reinstall the daily job-hunt schedule (macOS launchd). Usage: install.sh [HH:MM]   (default 08:40)
# Why an applet: macOS privacy protection (TCC) blocks launchd-spawned shells from reading ~/Documents, ~/Desktop and
# iCloud folders, where the repo or the hunt dir often live. A dedicated JobHunt.app asks for access once
# (macOS prompt → Allow), scoped to that app only; zsh/python/claude started by it inherit the grant.
# If no prompt appears and the log says "Operation not permitted": System Settings → Privacy & Security →
# Files and Folders (or Full Disk Access) → enable JobHunt.
set -eu
TIME="${1:-08:40}"
[[ "$TIME" =~ '^([01][0-9]|2[0-3]):[0-5][0-9]$' ]] || { echo "usage: install.sh [HH:MM]"; exit 2; }
HOUR=$((10#${TIME%%:*})); MINUTE=$((10#${TIME##*:}))
HERE="${0:A:h}"
APP="$HOME/Applications/JobHunt.app"
LABEL="local.jobhunt"
PLIST="$HOME/Library/LaunchAgents/$LABEL.plist"
STATE="$HOME/.local/state/jobhunt"
U="gui/$(id -u)"

mkdir -p "$HOME/Applications" "$HOME/Library/LaunchAgents" "$STATE"
rm -rf "$APP"
/usr/bin/osacompile -o "$APP" -e "do shell script \"/bin/zsh \" & quoted form of \"$HERE/run-daily.sh\" & \" >/dev/null 2>&1 || true\""
# Background-only: no Dock icon while the run takes its ~30 minutes.
/usr/bin/plutil -replace LSUIElement -bool true "$APP/Contents/Info.plist"
/usr/bin/codesign --force --sign - "$APP" 2>/dev/null || true

cat >"$PLIST" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by $HERE/install.sh. Run now: launchctl kickstart $U/$LABEL · remove: uninstall.sh -->
<plist version="1.0">
<dict>
  <key>Label</key><string>$LABEL</string>
  <key>ProgramArguments</key>
  <array><string>$APP/Contents/MacOS/applet</string></array>
  <!-- If the Mac is asleep at this time, launchd fires on wake. RunAtLoad covers days it was off (the run is idempotent per day). -->
  <key>StartCalendarInterval</key>
  <dict><key>Hour</key><integer>$HOUR</integer><key>Minute</key><integer>$MINUTE</integer></dict>
  <key>RunAtLoad</key><true/>
  <key>StandardOutPath</key><string>$STATE/launchd.out</string>
  <key>StandardErrorPath</key><string>$STATE/launchd.err</string>
  <key>ProcessType</key><string>Background</string>
</dict>
</plist>
EOF

launchctl bootout "$U/$LABEL" 2>/dev/null || true
launchctl bootstrap "$U" "$PLIST"
echo "installed: daily at $TIME → $APP (plist $PLIST)"
echo "RunAtLoad fires now (skipped if today's digest exists). Logs: $STATE/logs/"
